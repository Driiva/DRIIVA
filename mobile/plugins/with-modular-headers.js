/**
 * Expo config plugin: build the pods as static frameworks and stop -Werror
 * rejecting React Native's non-modular headers inside them.
 *
 * THE PROBLEM
 * @react-native-firebase pulls in Firebase's Swift pods. Under plain static
 * libraries CocoaPods will not even integrate them ("...which do not define
 * modules"), so `pod install` fails and the app cannot be built natively at
 * all. That is why no mobile screen in this lift had ever been seen running.
 *
 * WHY STATIC FRAMEWORKS RATHER THAN MODULAR HEADERS
 * Marking the Firebase pods `:modular_headers => true` gets pod install
 * through and then fails the compile with:
 *
 *   Pods/RNFBMessaging: 'FirebaseAuth/FirebaseAuth-Swift.h' file not found
 *   (Headers/Private/Firebase/Firebase.h:40)
 *
 * The decisive fact: FirebaseAuth-Swift.h does not exist ANYWHERE under
 * ios/Pods. Zero files. It is not missing from a search path, it is never
 * emitted. The Swift compiler only generates a pod's -Swift.h when that pod is
 * built as a module, and a static LIBRARY is not one. Adding more pods to a
 * modular_headers list therefore cannot fix it, which is exactly why two
 * successive attempts produced byte-identical errors.
 *
 * Static FRAMEWORKS do emit those generated headers, so `useFrameworks:
 * "static"` is the configuration that makes the umbrella header resolvable.
 *
 * WHY THE BUILD SETTING IS NEEDED WITH IT
 * On its own, static frameworks fails a third way: RNFBApp's headers import
 * <React/RCTConvert.h>, a non-modular header included from inside a framework
 * module, and -Werror promotes all six warnings to errors. Allowing that
 * specific include is the documented accompaniment, applied to every pod
 * target in post_install.
 *
 * gRPC is deliberately left alone throughout. Forcing it modular is what broke
 * an earlier attempt with 38 "gRPC-Core.modulemap not found" errors.
 *
 * WHY A PLUGIN AND NOT AN EDITED PODFILE
 * ios/ is gitignored and regenerated by every `expo prebuild`, so a hand edit
 * evaporates on the next clean build. A fix that does not survive prebuild is
 * not a fix.
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

const MARKER = '# driiva: static frameworks for the Firebase Swift pods';

const FRAMEWORKS_LINE = "use_frameworks! :linkage => :static";

/**
 * Applied to every pod target. RNFBApp is the one that needs it today, but
 * scoping it to a single pod would leave the next Firebase module to hit the
 * same wall on its own.
 */
const POST_INSTALL_PATCH = `
    # driiva: Firebase's pods are Swift and must build as modules for their
    # generated -Swift.h headers to exist at all. React Native's headers are
    # not modular, and importing one from inside a framework module is a
    # warning that -Werror turns into a build error. Allow it.
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |cfg|
        cfg.build_settings['CLANG_ALLOW_NON_MODULAR_INCLUDES_IN_FRAMEWORK_MODULES'] = 'YES'
      end
    end
`;

const withModularHeaders = (config) =>
  withDangerousMod(config, [
    'ios',
    (cfg) => {
      const podfilePath = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      let contents = fs.readFileSync(podfilePath, 'utf8');

      if (contents.includes(MARKER)) return cfg;

      const targetAnchor = /^(target ['"][^'"]+['"] do)$/m;
      if (!targetAnchor.test(contents)) {
        throw new Error(
          '[with-modular-headers] could not find the app target in the Podfile. ' +
            'The Expo Podfile template changed; update this plugin rather than ' +
            'hand-editing ios/Podfile, which prebuild regenerates.',
        );
      }
      contents = contents.replace(targetAnchor, `$1\n  ${MARKER}\n  ${FRAMEWORKS_LINE}`);

      // Splice into the EXISTING post_install rather than adding a second
      // block: CocoaPods honours only the last one declared, so a second block
      // would silently discard the Expo template's react_native_post_install.
      const postInstallAnchor = /^(\s*post_install do \|installer\|\n)/m;
      if (!postInstallAnchor.test(contents)) {
        throw new Error(
          '[with-modular-headers] could not find the post_install block in the ' +
            'Podfile. Update this plugin; do not add a second post_install, it ' +
            'would override the template one.',
        );
      }
      contents = contents.replace(postInstallAnchor, `$1${POST_INSTALL_PATCH}`);

      fs.writeFileSync(podfilePath, contents, 'utf8');
      return cfg;
    },
  ]);

module.exports = withModularHeaders;
