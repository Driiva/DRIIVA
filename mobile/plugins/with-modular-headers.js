/**
 * Expo config plugin: give the Firebase pods modular headers, and only them.
 *
 * THE PROBLEM
 * @react-native-firebase pulls in Firebase's Swift pods (FirebaseAuth,
 * FirebaseCoreInternal, FirebaseFirestore). Each depends on Objective-C pods
 * that define no module map, which CocoaPods refuses to integrate as static
 * libraries, so `pod install` fails outright:
 *
 *   The Swift pod `FirebaseAuth` depends upon `FirebaseAuthInterop`,
 *   `FirebaseAppCheckInterop`, `FirebaseCore`, `FirebaseCoreExtension`,
 *   `GoogleUtilities`, and `RecaptchaInterop`, which do not define modules.
 *
 * Until this was fixed the app could not be built natively at all, which is
 * why no mobile screen had ever been seen running.
 *
 * WHY TARGETED AND NOT GLOBAL
 * The obvious fix is a blanket `use_modular_headers!`. It does get `pod
 * install` through, and it is what the CocoaPods error itself suggests, but it
 * then fails the compile with 38 copies of:
 *
 *   error: module map file '.../Headers/Private/grpc/gRPC-Core.modulemap'
 *   not found (in target 'gRPC-C++')
 *
 * gRPC ships its own header layout and does not survive being forced into
 * modular headers. Firestore depends on gRPC, so the blanket switch breaks the
 * very pod it was meant to help. Listing the pods individually satisfies the
 * Swift pods and leaves gRPC alone, which is the arrangement react-native-
 * firebase documents.
 *
 * WHY A PLUGIN AND NOT AN EDITED PODFILE
 * ios/ is gitignored and regenerated by every `expo prebuild`, so a hand-edited
 * Podfile evaporates on the next clean build. A fix that does not survive
 * prebuild is not a fix. expo-build-properties has no equivalent option; its
 * `useFrameworks: "static"` is the other documented route and fails differently
 * again, with six non-modular-header errors inside RNFBApp because its headers
 * import <React/RCTConvert.h> under -Werror.
 */
const { withDangerousMod } = require('expo/config-plugins');
const fs = require('fs');
const path = require('path');

/**
 * The pods CocoaPods named as missing modules, the Firestore internals behind
 * the same complaint, and the three Swift pods themselves.
 *
 * FirebaseAuth, FirebaseFirestore and FirebaseMessaging are on this list for a
 * different reason to the rest. Marking only their DEPENDENCIES modular got the
 * build all the way to the final pods and then failed with:
 *
 *   Pods/RNFBMessaging: 'FirebaseAuth/FirebaseAuth-Swift.h' file not found
 *   (Headers/Private/Firebase/Firebase.h:40)
 *
 * FirebaseAuth is itself a Swift pod. The Firebase umbrella header imports its
 * generated -Swift.h, and that header only lands somewhere an importer can see
 * it when the pod is built with modular headers.
 *
 * Deliberately excludes gRPC-Core and gRPC-C++: see the note above.
 */
const MODULAR_PODS = [
  'FirebaseCore',
  'FirebaseCoreInternal',
  'FirebaseCoreExtension',
  'FirebaseAuth',
  'FirebaseAuthInterop',
  'FirebaseAppCheckInterop',
  'FirebaseFirestore',
  'FirebaseFirestoreInternal',
  'FirebaseMessaging',
  'GoogleUtilities',
  'RecaptchaInterop',
];

const MARKER = '# driiva: modular headers for the Firebase pods';

const withModularHeaders = (config) =>
  withDangerousMod(config, [
    'ios',
    (cfg) => {
      const podfilePath = path.join(cfg.modRequest.platformProjectRoot, 'Podfile');
      const contents = fs.readFileSync(podfilePath, 'utf8');

      if (contents.includes(MARKER)) return cfg;

      const anchor = /^(target ['"][^'"]+['"] do)$/m;
      if (!anchor.test(contents)) {
        throw new Error(
          '[with-modular-headers] could not find the app target in the Podfile. ' +
            'The Expo Podfile template changed; update this plugin rather than ' +
            'hand-editing ios/Podfile, which prebuild regenerates.',
        );
      }

      const block = [
        `  ${MARKER}`,
        ...MODULAR_PODS.map((pod) => `  pod '${pod}', :modular_headers => true`),
      ].join('\n');

      fs.writeFileSync(podfilePath, contents.replace(anchor, `$1\n${block}`), 'utf8');
      return cfg;
    },
  ]);

module.exports = withModularHeaders;
